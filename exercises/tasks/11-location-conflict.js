'use strict';

/**
 * Таск 11 — відповідь це не тільки тіло: заголовок Location і статус 409.
 *
 * Дві речі, яких твоєму POST /products зараз бракує.
 *
 * ПЕРШЕ: Location.
 * Коли сервер щось створив, він має сказати не тільки "готово", а й ДЕ це тепер
 * лежить. Для цього у відповіді ставлять заголовок:
 *
 *     Location: /products/7
 *
 * Клієнту не треба вгадувати адресу й складати її з шматків — сервер сам дав
 * посилання. Саме тому 201 і називається Created: створив і показав, де.
 *
 * ДРУГЕ: 409 Conflict.
 * Зараз можна створити десять продуктів з однаковою назвою. Зробимо назву
 * унікальною. І тут важливо не переплутати статуси:
 *
 *     400 Bad Request — запит кривий сам по собі: немає name, ціна текстом.
 *                       Скільки не повторюй — буде те саме.
 *     409 Conflict    — запит нормальний, але суперечить тому, що вже є.
 *                       Видали той продукт — і цей самий запит спрацює.
 *
 * ЩО ТРЕБА ЗРОБИТИ (в index.js, усе в POST /products)
 *
 *   1) на успішне створення додати заголовок:  res.set('Location', `/products/${id}`)
 *      (ставиться ДО res.status(201).json(...))
 *
 *   2) якщо продукт із такою назвою вже існує -> 409 і { error: "..." }
 *      Регістр не має значення: якщо є "Laptop", то "LAPTOP" — теж дублікат.
 *      Підказка: порівнюй обидві назви через .toLowerCase()
 *
 *   3) порядок перевірок: спочатку валідність тіла (400), і лише потім
 *      унікальність (409). Кривий запит не повинен доходити до перевірки
 *      на дублікат.
 */

/** Location може бути і відносним, і повним URL — нас цікавить хвіст. */
const pointsTo = (location, id) =>
  typeof location === 'string' && new RegExp(`/products/${id}$`).test(location);

module.exports = {
  id: '11',
  type: 'code',
  title: 'Location, 409 Conflict та ідемпотентність',

  brief: `
    Редагуєш файл:  index.js  (тільки POST /products)

    1) На успішне створення додай заголовок Location з адресою нової речі:
         res.set('Location', \`/products/\${newProduct.id}\`);
       Ставиться ДО res.status(201).json(...)

    2) Назва продукту стає унікальною. Дублікат -> 409 і { error }.
       Регістр не важливий: якщо є "Laptop", то "LAPTOP" — теж дублікат.

    3) Порядок: спочатку перевірка тіла (400), потім перевірка на дублікат (409).

    Різниця, заради якої все це:
      400 — запит кривий сам по собі, повторювати марно
      409 — запит нормальний, але суперечить тому, що вже існує
  `,

  async run(t) {
    const created = await t.api('POST', '/products', { name: 'Laptop', price: 1200 });
    if (created.status !== 201) {
      t.blocked(
        `POST /products відповів ${created.status} замість 201.\n` +
          '    Спочатку доведи до зеленого таск 06.'
      );
    }
    const id = created.body.id;
    const location = created.headers.location;

    t.check(
      `POST /products -> 201 із заголовком Location: /products/${id}`,
      pointsTo(location, id),
      `а Location = ${location === undefined ? '(заголовка немає)' : location}\n` +
        'Додай перед відповіддю:  res.set(\'Location\', `/products/${newProduct.id}`)'
    );

    if (pointsTo(location, id)) {
      const followed = await t.api('GET', new URL(location, 'http://localhost').pathname);
      t.check(
        'За адресою з Location справді лежить щойно створений продукт',
        followed.status === 200 && followed.body && followed.body.id === id,
        `а GET ${location} відповів ${followed.status}: ${followed.text.slice(0, 120)}`
      );
    }

    // --- дублікати ---
    const duplicate = await t.api('POST', '/products', { name: 'Laptop', price: 50 });
    t.check(
      'POST з уже існуючою назвою "Laptop" -> 409 і { error }',
      duplicate.status === 409 && duplicate.body && typeof duplicate.body.error === 'string',
      `а прийшло ${duplicate.status}, відповідь: ${duplicate.text.slice(0, 120)}\n` +
        'Це не 400: саме тіло запиту нормальне. Конфлікт не з запитом,\n' +
        'а з тим, що вже лежить у масиві.'
    );

    const otherCase = await t.api('POST', '/products', { name: 'LAPTOP', price: 50 });
    t.check(
      'POST з назвою "LAPTOP" (інший регістр) -> теж 409',
      otherCase.status === 409,
      `а прийшло ${otherCase.status}, відповідь: ${otherCase.text.slice(0, 120)}\n` +
        'Порівнюй назви через .toLowerCase() з обох боків.'
    );

    const brokenDuplicate = await t.api('POST', '/products', { name: 'Laptop', price: -5 });
    t.check(
      'POST з існуючою назвою І поганою ціною -> 400 (тіло перевіряємо першим)',
      brokenDuplicate.status === 400,
      `а прийшло ${brokenDuplicate.status}, відповідь: ${brokenDuplicate.text.slice(0, 120)}\n` +
        'Спочатку перевіряємо, чи запит узагалі валідний, і лише потім —\n' +
        'чи не конфліктує він з наявними даними.'
    );

    const another = await t.api('POST', '/products', { name: 'Mouse', price: 25 });
    t.check(
      'POST з іншою назвою "Mouse" усе ще створюється: 201',
      another.status === 201,
      `а прийшло ${another.status}, відповідь: ${another.text.slice(0, 120)}\n` +
        'Перевірка на дублікат не має блокувати нормальні запити.'
    );

    // --- ідемпотентність видалення ---
    const removed = await t.api('DELETE', `/products/${id}`);
    t.check(
      'DELETE існуючого продукту -> 204',
      removed.status === 204,
      `а прийшло ${removed.status}`
    );

    const removedAgain = await t.api('DELETE', `/products/${id}`);
    t.check(
      'DELETE того самого вдруге -> 404',
      removedAgain.status === 404,
      `а прийшло ${removedAgain.status}`
    );

    const reused = await t.api('POST', '/products', { name: 'Laptop', price: 1500 });
    t.check(
      'Після видалення назву "Laptop" знову можна зайняти: 201',
      reused.status === 201,
      `а прийшло ${reused.status}, відповідь: ${reused.text.slice(0, 120)}\n` +
        'Унікальність рахується серед ТЕПЕРІШНІХ продуктів. Видалений\n' +
        'більше нікому не заважає.'
    );

    t.check(
      'Новий "Laptop" отримав новий id, а не той самий',
      reused.body && reused.body.id !== id,
      `а id знову ${id} — це урок з таска 04: лічильник не має ходити по колу.`
    );
  },

  explain: `
    Три речі.

    1. Відповідь — це статус + заголовки + тіло. Тіло ти вже відчула, статус теж,
       а заголовки поки лишались невидимими. Location на 201 — найкорисніший із
       них: "я створив, ось де воно тепер живе". Клієнту не треба здогадуватись,
       як зібрати адресу, і якщо завтра адреси зміняться (/products -> /v2/items),
       той, хто читає Location, не зламається.

    2. 400 і 409 відповідають на різні питання.
         400: "твій запит неправильний" — виправ запит.
         409: "твій запит правильний, але зараз так не можна" — виправ СТАН
              (видали дублікат) або змінись сам (візьми іншу назву).
       Фронт реагує на них по-різному: на 400 підсвічує поле, на 409 показує
       "таке ім'я вже зайняте". Якщо все звалити в 400, фронт не зможе відрізнити.

    3. Ідемпотентність — слово, яке звучить страшно, а означає просте:
       "повтори скільки хочеш, результат не зміниться".

         GET    — ідемпотентний. Читання нічого не змінює.
         PUT    — ідемпотентний. Описує кінцевий стан.
         DELETE — ідемпотентний ПО СУТІ: після першого разу продукту немає,
                  і після п'ятого його теж немає. Стан однаковий.
         POST   — НІ. Два POST — два продукти.

       Чому це не теорія. Уяви: клієнт надіслав POST, сервер створив продукт —
       і тут обірвався інтернет. Клієнт не отримав відповіді й не знає, чи
       дійшло. Повторить — буде два продукти. Саме тому в серйозних API до
       POST додають заголовок Idempotency-Key: клієнт генерує унікальний ключ,
       сервер запам'ятовує його і на повтор із тим самим ключем віддає ту саму
       відповідь замість створення другої речі. Так працюють усі платіжні API.

       До речі, про повторний DELETE сперечаються досі. Ми віддаємо 404
       ("такого немає" — чесно), але є школа, що правильніше 204 ("його немає,
       а ти саме цього й хотіла"). Обидва варіанти живі; головне — вибрати один
       і тримати його в усьому API.
  `,
};
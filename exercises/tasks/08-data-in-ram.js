'use strict';

/**
 * Таск 08 — тут нічого не треба писати.
 *
 * Просто запусти і подивись, що станеться:
 *
 *     node exercises/run.js 08
 *
 * Це підготовка до наступної теми.
 */

module.exports = {
  id: '08',
  type: 'demo',
  title: 'Куди зникають дані після перезапуску',

  brief: `
    Тут нічого писати не треба.

    Просто натисни Enter і подивись, що станеться: перевірка створить
    користувача, перезапустить сервер і покаже результат.

    Це підготовка до наступної теми.
  `,

  async run(t) {
    const before = (await t.api('GET', '/users')).body;
    t.info(
      `1. Сервер щойно запустився. Користувачів: ${before.length} -> ${before
        .map((u) => u.name)
        .join(', ')}`
    );

    await t.api('POST', '/users', { name: 'Назавжди', email: 'forever@example.com' });
    const afterCreate = (await t.api('GET', '/users')).body;
    t.info(
      `2. Створили нового користувача. Тепер їх ${afterCreate.length} -> ${afterCreate
        .map((u) => u.name)
        .join(', ')}`
    );
    t.info('   Сервер відповів 201, у списку він є. Виглядає так, ніби все збереглось.');

    t.info('3. Зупиняємо node і запускаємо index.js заново...');
    await t.restart();

    const afterRestart = (await t.api('GET', '/users')).body;
    t.info(
      `4. Після перезапуску користувачів: ${afterRestart.length} -> ${afterRestart
        .map((u) => u.name)
        .join(', ')}`
    );
    t.info('');

    t.check(
      'Користувач "Назавжди" після перезапуску зник',
      !afterRestart.some((u) => u.name === 'Назавжди'),
      'Несподівано — він вижив. Отже, ти вже десь зберігаєш дані не тільки в масиві.\nРозкажи про це на зустрічі.'
    );

    t.check(
      'Список повернувся рівно до того, що записано в index.js',
      afterRestart.length === before.length,
      `було ${before.length}, стало ${afterRestart.length}`
    );

    t.info('');
    t.info('Спробуй відповісти собі на ці питання ДО того, як читати пояснення нижче:');
    t.info('  - Чому користувач зник, хоча сервер відповів 201 і в списку він був?');
    t.info('  - Що сталося з масивом users у момент, коли node зупинився?');
    t.info('  - А що буде, якщо запустити ДВА такі сервери одночасно на різних');
    t.info('    портах і створити користувача тільки в одному з них?');
  },

  explain: `
    const users = [...] — це звичайна змінна всередині запущеної програми node.
    Вона живе в оперативній пам'яті — тій, яку комп'ютер виділив саме цій
    програмі, поки вона працює. Програма зупинилась — пам'ять повернулась
    системі разом з усіма твоїми користувачами.

    Тому 201 у відповіді означав лише "я додав у масив", а не "я зберіг".

    Звідси два наслідки, і другий важливіший за перший.

    1. Дані не переживають перезапуск. А перезапуск буває постійно: оновили код,
       щось впало, сервер перезавантажили.

    2. Дані не переживають ДРУГУ КОПІЮ програми. Уяви, що користувачів стало
       багато і ми запустили два однакові сервери поруч. У кожного буде СВІЙ
       окремий масив users. Створила користувача на першому — другий про нього
       навіть не здогадується. Тобто такий застосунок неможливо "розмножити",
       щоб він витримував більше навантаження.

    Рішення — винести дані з програми назовні, у щось окреме, що вміє:
      - зберігати на диск (і переживати перезапуски),
      - віддавати всім копіям програми однакові дані,
      - швидко шукати потрібне серед мільйонів записів.

    Це і є база даних. Наступний крок — PostgreSQL. Робити будеш той самий CRUD,
    просто замість users.push() буде команда INSERT, а замість users.find() —
    команда SELECT.
  `,
};
